#!/usr/bin/env python3
"""Write deploy/smilecdr/mapped-files.yaml, the Smile CDR chart's mappedFiles values.

The Smile CDR chart mounts each `mappedFiles` entry into the pod from a ConfigMap
whose name carries a hash of the file's content. Helm values cannot read files,
so the Argo CD Application (aehrc/sparked-argo apps/smilecdr.yaml) layers this
generated values file over module-config/*.yaml, and terraform/main.tf reads the
same file for the sdh-deps module's helm_chart_values (the cross-check), so this
script's list is the only list.

The bytes must match the source files exactly: a changed trailing newline is a new
ConfigMap name, a new pod template and a Smile CDR restart. Every write is parsed
back and compared byte for byte before it is kept.

Usage:
  python3 scripts/render_smile_mapped_files.py          # write the file
  python3 scripts/render_smile_mapped_files.py --check  # exit 1 if it is stale

To add or remove a mapped file, edit MAPPED_FILES below, run the script and commit
both. CI (validate-config.yml) runs --check on every pull request.
"""

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "deploy" / "smilecdr" / "mapped-files.yaml"
SEEDING = "/home/smile/smilecdr/classes/config_seeding"

# (name in the pod, source file relative to the repository root, mount directory).
# The order is the order of the output file only; Helm treats mappedFiles as a map.
MAPPED_FILES = [
    # Package specifications installed at startup.
    ("package-international-patient-summary-2.0.1.json", "module-config/packages/package-international-patient-summary-2.0.1.json", SEEDING),
    ("package-international-patient-summary-2.0.0.json", "module-config/packages/package-international-patient-summary-2.0.0.json", SEEDING),
    ("package-aucore-2.1.0-draft.json", "module-config/packages/package-aucore-2.1.0-draft.json", SEEDING),
    ("package-au-base-6.1.1-draft.json", "module-config/packages/package-au-base-6.1.1-draft.json", SEEDING),
    ("package-au-erequesting-1.0.0.json", "module-config/packages/package-au-erequesting-1.0.0.json", SEEDING),
    ("package-au-patient-summary-1.0.0.json", "module-config/packages/package-au-patient-summary-1.0.0.json", SEEDING),
    ("package-au-base-7.0.0-ballot1.json", "module-config/packages/package-au-base-7.0.0-ballot1.json", SEEDING),
    ("package-aucore-3.0.0-ballot1.json", "module-config/packages/package-aucore-3.0.0-ballot1.json", SEEDING),
    ("package-hl7-terminology-7.3.0.json", "module-config/packages/package-hl7-terminology-7.3.0.json", SEEDING),
    ("package-smart-app-launch-2.2.0.json", "module-config/packages/package-smart-app-launch-2.2.0.json", SEEDING),
    # SMART post-authorize callback (post_authorize_script.file on smart_auth).
    ("smart-post-authorize.js", "module-config/smart-post-authorize.js", SEEDING),
    # Consent service enforcing the read-only DEFAULT partition (ADR 0001),
    # consent_service.script.file on the aucore fhir_endpoint module.
    ("consent-default-readonly.js", "module-config/consent-default-readonly.js", SEEDING),
]

HEADER = """\
# GENERATED by scripts/render_smile_mapped_files.py. Do not edit by hand: edit the
# source files under module-config/ (or the list in the script), run the script and
# commit both. CI fails a pull request whose copy here is stale.
#
# Read by the Argo CD Application smilecdr (aehrc/sparked-argo apps/smilecdr.yaml)
# after module-config/values-common.yaml, simplified-multinode.yaml and
# values-sparkey.yaml. Each `data` is the source file's exact bytes: the chart
# hashes it into a ConfigMap name, so any change here restarts Smile CDR.
"""


def block_scalar(text: str, indent: str) -> str:
    """A YAML literal block for text, or a double-quoted scalar when a block cannot hold it exactly."""
    lines = text.split("\n")
    plain_ok = (
        text.endswith("\n")
        and not text.endswith("\n\n")
        and "\r" not in text
        and not text.startswith((" ", "\n"))
        and all(line == line.rstrip(" \t") for line in lines)
    )
    if plain_ok:
        body = "\n".join((indent + line) if line else "" for line in lines[:-1])
        return "|\n" + body + "\n"
    return yaml.safe_dump(text, default_style='"', width=1 << 20).rstrip("\n").removesuffix("\n...") + "\n"


def render() -> str:
    out = [HEADER, "mappedFiles:\n"]
    for name, src, path in MAPPED_FILES:
        data = (ROOT / src).read_text(encoding="utf-8")
        out.append(f"  {name}:\n")
        out.append(f"    path: {path}\n")
        out.append("    data: " + block_scalar(data, "      "))
    text = "".join(out)
    parsed = yaml.safe_load(text)["mappedFiles"]
    for name, src, path in MAPPED_FILES:
        want = (ROOT / src).read_bytes()
        got = parsed[name]["data"].encode("utf-8")
        if got != want or parsed[name]["path"] != path:
            sys.exit(f"render_smile_mapped_files: {name} does not round-trip byte for byte")
    if len(parsed) != len(MAPPED_FILES):
        sys.exit("render_smile_mapped_files: duplicate names in MAPPED_FILES")
    return text


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file is stale")
    args = ap.parse_args()

    text = render()

    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 scripts/render_smile_mapped_files.py and commit it", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date ({len(MAPPED_FILES)} files)")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(MAPPED_FILES)} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
